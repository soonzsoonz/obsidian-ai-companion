dir_path = 'src/i18n/locales'
for filename in os.listdir(dir_path):
    if not filename.endswith('.ts') or filename in ['en.ts', 'zh_tw.ts', 'zh_cn.ts']:
        continue
    
    lang = filename.replace('.ts', '')
    if lang not in translations:
        print(f'Warning: No translations for {lang}')
        continue
        
    filepath = os.path.join(dir_path, filename)
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
        
    for key, value in translations[lang].items():
        if "'" in value:
            safe_value = value.replace('"', '\\"')
            replacement = f"{key}: \"{safe_value}\","
        else:
            replacement = f"{key}: '{value}',"
            
        pattern = r"^\s*" + key + r"\s*:\s*['\"].*?['\"],\s*$"
        content = re.sub(pattern, f"  {replacement}", content, flags=re.MULTILINE)
        
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(content)
        
print('Done processing files.')
